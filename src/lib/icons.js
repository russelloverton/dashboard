/**
 * Map WMO weather code to the appropriate icon component.
 */
export function WeatherIcon({ code, size = 20, className = '' }) {
  if (code === 0) return <IconSun size={size} className={className} />;
  if (code <= 2) return <IconSunCloud size={size} className={className} />;
  if (code === 3) return <IconCloud size={size} className={className} />;
  if (code <= 48) return <IconCloudFog size={size} className={className} />;
  if (code <= 57) return <IconCloudDrizzle size={size} className={className} />;
  if (code <= 67) return <IconCloudRain size={size} className={className} />;
  if (code <= 77) return <IconCloudSnow size={size} className={className} />;
  if (code <= 82) return <IconCloudRain size={size} className={className} />;
  if (code <= 86) return <IconCloudSnow size={size} className={className} />;
  if (code <= 99) return <IconCloudLightning size={size} className={className} />;
  return <IconThermometer size={size} className={className} />;
}
